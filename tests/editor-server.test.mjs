test('local JSON workflow saves incomplete drafts, commits natively and prevents stale overwrites', async t => {
  const root = await fs.mkdtemp(path.join(os.tmpdir(),'financing-server-test-'));
  for (const dir of ['data/holdings','config']) await fs.mkdir(path.join(root,dir),{recursive:true});
  await fs.writeFile(path.join(root,'data/holdings/current.json'),JSON.stringify({...previous,snapshot_date:null}));
  await fs.writeFile(path.join(root,'config/investment-mandate.json'),JSON.stringify(mandate));
  await fs.copyFile(new URL('../持仓填写.html',import.meta.url),path.join(root,'持仓填写.html'));
  const server = await startHoldingsServer({root,port:0,lookupFund:async code=>({code,name:'查询到的基金A',source:'测试来源'})});
  t.after(()=>new Promise(resolve=>{server.close(resolve);server.closeAllConnections();}));
  const url=`http://127.0.0.1:${server.address().port}`;
  assert.equal((await fetch(url+'/api/fund?code=123')).status,400);
  assert.equal((await fetch(url+'/api/fund?code=000032',{method:'POST'})).status,405);
  assert.equal((await fetch(url+'/api/fund?code=000032',{headers:{Origin:'https://example.org'}})).status,403);
  assert.deepEqual(await (await fetch(url+'/api/fund?code=000032')).json(),{code:'000032',name:'查询到的基金A',source:'测试来源'});
  const get=()=>fetch(url+'/api/holdings').then(r=>r.json());
  const put=(document,revision,mode='draft',origin=url)=>fetch(url+'/api/holdings',{method:'PUT',headers:{'Content-Type':'application/json',Origin:origin},body:JSON.stringify({document,revision,mode,api_version:editorApiVersion()})});
  let loaded=await get();
  assert.equal(loaded.api_version,editorApiVersion());
  const oldPage=await fetch(url+'/api/holdings',{method:'PUT',headers:{'Content-Type':'application/json'},body:JSON.stringify({document:loaded.document,revision:loaded.revision,mode:'draft'})});
  assert.equal(oldPage.status,409);
  assert.equal((await get()).revision,loaded.revision);
  assert.equal(loaded.document.holdings.length,25);
  assert.equal(loaded.document.holdings[0].amount_cny,null);
  assert.equal(loaded.document.holdings[0].previous_amount_cny,1000);
  loaded.document.holdings[0].batches=[{units:null,holding_days:9,redemption_fee_pct:0.5}];
  loaded.document.holdings[0].holding_pnl_cny='-123.45';
  loaded.document.holdings[0].holding_return_pct='-1.25';
  const stale=loaded.revision;
  const savedResponse=await put(loaded.document,loaded.revision);
  assert.equal(savedResponse.status,200);
  const saved=await savedResponse.json();
  assert.equal(saved.document.status,'draft');
  assert.equal(saved.document.holdings[0].holding_pnl_cny,-123.45);
  assert.equal((await get()).document.holdings[0].holding_return_pct,-1.25);
  const draftBatch=JSON.parse(await fs.readFile(path.join(root,'每日持仓.json'),'utf8')).holdings[0].batches[0];
  assert.equal(draftBatch.holding_days_min,9);
  assert.equal(draftBatch.holding_days_max,9);
  assert.ok(!Object.hasOwn(draftBatch,'holding_days'));
  assert.equal(JSON.parse(await fs.readFile(path.join(root,'data/holdings/current.json'),'utf8')).snapshot_date,null);
  assert.equal((await put(saved.document,stale)).status,409);
  assert.equal((await put(saved.document,saved.revision,'draft','https://example.org')).status,403);
  assert.equal((await put(saved.document,saved.revision,'commit')).status,400);
  loaded=await get();
  const doc=loaded.document;
  doc.snapshot_date=new Date().toLocaleDateString('en-CA',{timeZone:'Asia/Hong_Kong'});doc.cash.amount_cny=1000;
  doc.holdings.forEach(h=>{h.amount_cny=120;h.batches=[{units:50,holding_days:9,redemption_fee_pct:0.5},{units:50,holding_days:100,redemption_fee_pct:0}];});
  doc.holdings[0].batches=[{units:50,holding_days_min:7,holding_days_max:59,redemption_fee_pct:0.5},{units:50,holding_days_min:60,holding_days_max:null,redemption_fee_pct:0}];
  doc.holdings[0].unit_nav=1.2;doc.holdings[0].nav_date=doc.snapshot_date;
  const committedResponse=await put(doc,loaded.revision,'commit');
  assert.equal(committedResponse.status,200);
  const committed=await committedResponse.json();
  assert.equal(committed.document.status,'validated');
  const state=JSON.parse(await fs.readFile(path.join(root,'data/holdings/current.json'),'utf8'));
  assert.equal(state.fund_plus_available_cash_cny,4000);
  assert.equal(state.holdings[0].batches[0].redemption_fee_pct,0.5);
  assert.deepEqual(state.holdings[0].batches.map(b=>[b.holding_days_min,b.holding_days_max]),[[7,59],[60,null]]);
  assert.deepEqual((await get()).document.holdings[0].batches.map(b=>[b.holding_days_min,b.holding_days_max]),[[7,59],[60,null]]);
  assert.equal(state.holdings[0].unit_nav,1.2);
  assert.equal(state.holdings[0].holding_pnl_cny,-123.45);
  assert.equal(state.holdings[0].holding_return_pct,-1.25);
  assert.equal(typeof state.holdings[0].estimated_holding_return_pct,'number');
  assert.equal((await get()).document.holdings[0].holding_pnl_cny,-123.45);
  assert.equal(state.holdings[0].notes,'');
  assert.deepEqual(state.missing_execution_fields,[]);
  assert.equal(await fs.readFile(path.join(root,state.source_archive),'utf8'),await fs.readFile(path.join(root,'每日持仓.json'),'utf8'));
  assert.ok((await fs.readdir(path.join(root,'data/holdings/input-history'))).length>=2);
  const before=await fs.readFile(path.join(root,'每日持仓.json'),'utf8');
  const badPnl=structuredClone(committed.document);badPnl.holdings[0].holding_pnl_cny='bad';
  assert.equal((await put(badPnl,committed.revision,'commit')).status,400);
  assert.equal(await fs.readFile(path.join(root,'每日持仓.json'),'utf8'),before);
  committed.document.holdings[0].batches[0].redemption_fee_pct=101;
  assert.equal((await put(committed.document,committed.revision,'commit')).status,400);
  assert.equal(await fs.readFile(path.join(root,'每日持仓.json'),'utf8'),before);
  // A manual change to the JSON is read immediately and also invalidates old revisions.
  const manual=JSON.parse(before);manual.cash.notes='手工修改';
  await fs.writeFile(path.join(root,'每日持仓.json'),JSON.stringify(manual));
  assert.equal((await get()).document.cash.notes,'手工修改');
  assert.equal((await put(manual,committed.revision)).status,409);
  assert.equal((await fetch(url+'/data/holdings/current.json')).status,404);
});
test('native JSON validation enforces identities, dates, amount and batch constraints',()=>{
  const base={format:'financing-holdings-editor-v1',snapshot_date:'2026-10-08',cash:{amount_cny:0},holdings:previous.holdings.map(h=>({...h,all_redeemable:true,batches:[],amount_cny:1}))};
  const parse=doc=>parseEditorJson(doc,{...previous,snapshot_date:null},mandate,'2026-10-08');
  assert.equal(parse(base).strategy_cash.amount_cny,0);
  const mutate=fn=>{const doc=structuredClone(base);fn(doc);return doc;};
  assert.equal(parse(mutate(d=>d.holdings.pop())).holdings.length,24);
  assert.throws(()=>parse(mutate(d=>d.holdings[0].id=d.holdings[1].id)),/重复/);
  assert.throws(()=>parse(mutate(d=>d.holdings[0].code='12345')),/六位数字/);
  assert.throws(()=>parse(mutate(d=>d.holdings[0].name='')),/名称和平台不能为空/);
  assert.throws(()=>parse(mutate(d=>d.snapshot_date='2026-02-30')),/有效日期/);
  assert.throws(()=>parse(mutate(d=>d.holdings[0].nav_date='2026-10-09')),/不能晚于/);
  assert.throws(()=>parse(mutate(d=>d.holdings[0].batches=[{units:1,holding_days:1.5,redemption_fee_pct:0}])),/天数须为整数/);
  assert.throws(()=>parse(mutate(d=>{d.holdings[0].all_redeemable=false;d.holdings[0].redeemable_units=2;d.holdings[0].batches=[{units:1}];})),/超过总份额/);
  assert.throws(()=>parse(mutate(d=>{d.holdings[0].amount_cny=0;d.holdings[0].batches=[{units:1}];})),/金额为0/);
  assert.throws(()=>parse(mutate(d=>d.cash.amount_cny=-1)),/非负数字/);
  assert.throws(()=>parseEditorJson(base,{...previous,snapshot_date:'2026-10-09'},mandate,'2026-10-10'),/较早日期/);
  const tiny=mutate(d=>d.holdings[0].unit_nav=0.00000001);tiny.holdings[0].nav_date='2026-10-08';
  const normalized=validateEditorDocument(tiny,previous.holdings,mandate.allowed_fund_codes,{today:'2026-10-08'});
  assert.doesNotThrow(()=>parse(normalized));
});
