const date=new Date().toLocaleDateString('en-CA',{timeZone:'Asia/Hong_Kong'});
function doc(){const input=createEditorDocument({...current,snapshot_date:null});input.snapshot_date=date;input.cash.amount_cny=1000;input.holdings.forEach(h=>{h.amount_cny=100;h.batches=[{units:50,holding_days:30,redemption_fee_pct:0}];});return input;}
const added=()=>({id:'I_new',code:'000001',name:'用户新投资A',platform:'新平台',category:'bond',analysis_enabled:true,amount_cny:300,all_redeemable:true,batches:[{units:200,holding_days:10,redemption_fee_pct:0.5}]});
test('add and delete investments, preserve exclusions and use only active amounts and missing fields',()=>{
 const input=doc();const removed=input.holdings.pop();const excluded=input.holdings[0];
 excluded.analysis_enabled=false;excluded.excluded_reason='暂不纳入本次分析';excluded.amount_cny=null;excluded.batches=[{units:null,holding_days:3,redemption_fee_pct:null}];excluded.pending_buy_cny=10000;
 input.holdings.push(added());
 const snapshot=parseEditorJson(input,{...current,snapshot_date:null},mandate,date);
 assert.equal(snapshot.holdings.length,24);assert.equal(snapshot.excluded_holdings.length,1);
 assert.equal(snapshot.excluded_holdings[0].id,excluded.id);assert.equal(snapshot.excluded_holdings[0].amount_cny,null);
 assert.equal(snapshot.fund_total_cny,2600);assert.equal(snapshot.fund_plus_available_cash_cny,3600);
 assert.deepEqual(snapshot.removed_holding_ids,[removed.id]);assert.ok(snapshot.analysis_fund_codes.includes('000001'));
 assert.deepEqual(snapshot.missing_execution_fields,[]);assert.equal(snapshot.pending_buy_total_cny,null);
 assert.doesNotThrow(()=>validateSnapshot(snapshot));
 const restore=structuredClone(input);restore.holdings[0].analysis_enabled=true;
 assert.throws(()=>parseEditorJson(restore,snapshot,mandate,date),/持有金额不能为空/);
 restore.holdings[0].amount_cny=50;restore.holdings[0].batches=[{units:25,holding_days:30,redemption_fee_pct:0}];
 const restored=parseEditorJson(restore,snapshot,mandate,date);
 assert.equal(restored.holdings.length,25);assert.equal(restored.excluded_holdings.length,0);assert.equal(restored.fund_total_cny,2650);
});
