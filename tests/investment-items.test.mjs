test('JSON store persists new and deleted identities in drafts and commits; history remains recoverable',async()=>{
 const root=await fs.mkdtemp(path.join(os.tmpdir(),'financing-items-test-'));
 for(const directory of ['data/holdings','config'])await fs.mkdir(path.join(root,directory),{recursive:true});
 await fs.writeFile(path.join(root,'data/holdings/current.json'),JSON.stringify({...current,snapshot_date:null}));
 await fs.writeFile(path.join(root,'config/investment-mandate.json'),JSON.stringify(mandate));
 const store=createEditorStore(root);await store.initialize();let loaded=await store.load();
 const input=doc();input.holdings.pop();input.holdings.unshift(added());input.holdings[1].analysis_enabled=false;input.holdings[1].amount_cny=null;
 const saved=await store.save(input,loaded.revision,'draft');loaded=await store.load();
 assert.equal(loaded.document.holdings[0].code,'000001');assert.equal(loaded.document.holdings[1].analysis_enabled,false);assert.equal(loaded.revision,saved.revision);
 await store.save(loaded.document,loaded.revision,'commit');loaded=await store.load();assert.equal(loaded.document.holdings.length,25);
 const snapshot=JSON.parse(await fs.readFile(path.join(root,'data/holdings/current.json'),'utf8'));
 assert.equal(snapshot.holdings.length,24);assert.equal(snapshot.excluded_holdings.length,1);assert.equal(snapshot.holdings[0].id,'I_new');
 const histories=await fs.readdir(path.join(root,'data/holdings/input-history'));assert.ok(histories.length>=2);
 const oldDocuments=await Promise.all(histories.map(file=>fs.readFile(path.join(root,'data/holdings/input-history',file),'utf8').then(JSON.parse)));
 assert.ok(oldDocuments.some(d=>d.holdings.some(h=>h.id===current.holdings.at(-1).id)));
});
